    /// The glyph a notice or a tag in `tone` carries.
    pub const fn for_tone(tone: super::Tone) -> Icon {
        match tone {
            super::Tone::Danger => Icon::CircleAlert,
            super::Tone::Warning => Icon::TriangleAlert,
            super::Tone::Success => Icon::CircleCheck,
            _ => Icon::Info,
        }
    }
