//! Renders the parsed contract into C headers, and computes the struct layouts
//! the generated `slopos-abi` pins assert against.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::contract::Const;
use crate::contract::Field;
use crate::contract::Signature;
use crate::contract::Struct;
use crate::ctype;
use crate::ctype::Types;
use crate::decls::HeaderSpec;

/// Typedefs the compiler's own `<stddef.h>` also defines, and the guard macro
/// it sets. Both headers reach one translation unit — `<locale.h>` takes
/// `NULL` from `<stddef.h>` — and a repeated typedef is an error before C11.
const STDDEF_TYPEDEFS: &[(&str, &str)] = &[("size_t", "_SIZE_T"), ("wchar_t", "_WCHAR_T")];

/// Identifiers C accepts and C++ reserves. A typedef named one of these is
/// emitted for C only; a parameter named one of these is a generation error,
/// because the fix belongs at the declaration rather than in a rename the
/// header would then disagree with.
const CXX_KEYWORDS: &[&str] = &[
    "and",
    "and_eq",
    "bitand",
    "bitor",
    "bool",
    "catch",
    "char16_t",
    "char32_t",
    "char8_t",
    "class",
    "compl",
    "concept",
    "const_cast",
    "consteval",
    "constexpr",
    "constinit",
    "decltype",
    "delete",
    "dynamic_cast",
    "explicit",
    "export",
    "false",
    "friend",
    "mutable",
    "namespace",
    "new",
    "noexcept",
    "not",
    "not_eq",
    "nullptr",
    "operator",
    "or",
    "or_eq",
    "private",
    "protected",
    "public",
    "reinterpret_cast",
    "requires",
    "static_assert",
    "static_cast",
    "template",
    "this",
    "thread_local",
    "throw",
    "true",
    "try",
    "typeid",
    "typename",
    "using",
    "virtual",
    "wchar_t",
    "xor",
    "xor_eq",
];

/// A type the headers can define.
pub enum TypeDef<'a> {
    Alias {
        name: &'a str,
        underlying: &'a str,
    },
    Struct(&'a Struct),
    /// An incomplete type: `FILE`, `DIR`.
    Opaque(&'a str),
    /// A literal C line, for `va_list`.
    Raw(&'a str),
}

/// Everything a header needs to render, looked up by name.
pub struct World<'a> {
    pub types: Types,
    pub type_defs: BTreeMap<&'a str, TypeDef<'a>>,
    pub consts: BTreeMap<&'a str, &'a Const>,
    pub slibc_consts: BTreeMap<String, (String, String)>,
    pub macros: BTreeMap<&'a str, &'a Signature>,
    pub macro_bodies: BTreeMap<&'a str, &'a str>,
    pub functions: BTreeMap<&'a str, &'a Signature>,
    pub statics: BTreeMap<&'a str, &'a Field>,
    pub source: String,
}

impl World<'_> {
    /// Renders one header in full.
    pub fn render(&self, spec: &HeaderSpec) -> Result<String, String> {
        let guard = guard_name(spec.path);
        let mut out = String::new();
        let _ = writeln!(out, "/* {} — {}.", spec.path, spec.summary);
        let _ = writeln!(out, " *");
        let _ = writeln!(
            out,
            " * Generated by slibc/build.rs from {}; do not edit.",
            self.source
        );
        let _ = writeln!(
            out,
            " * Every type, constant and prototype below is the SlopOS `libc` module's own"
        );
        let _ = writeln!(
            out,
            " * declaration, so a C consumer and Rust's `std` see one ABI."
        );
        let _ = writeln!(out, " */");
        let _ = writeln!(out, "#ifndef {guard}");
        let _ = writeln!(out, "#define {guard}");

        if !spec.includes.is_empty() {
            out.push('\n');
            for include in spec.includes {
                let _ = writeln!(out, "#include <{include}>");
            }
        }

        // Ahead of the linkage block, not inside it: `raw` carries macros,
        // typedefs and `#include_next`, and a header reached through one of
        // those would have every declaration in it given C linkage.
        if !spec.raw.is_empty() {
            out.push('\n');
            for line in spec.raw {
                let _ = writeln!(out, "{line}");
            }
        }

        // Only what C++ would otherwise mangle needs the linkage block; a
        // header of typedefs and macros gets an empty one otherwise.
        let declares_symbols =
            !spec.functions.is_empty() || !spec.extra.is_empty() || !spec.variables.is_empty();
        if declares_symbols {
            out.push_str("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
        }

        if !spec.types.is_empty() {
            out.push('\n');
            for name in spec.types {
                let def = self
                    .type_defs
                    .get(name)
                    .ok_or_else(|| format!("{}: unknown type `{name}`", spec.path))?;
                out.push_str(&self.render_type(def)?);
            }
        }

        if !spec.consts.is_empty() || !spec.slibc_consts.is_empty() {
            out.push('\n');
            for name in spec.slibc_consts {
                let (ty, expr) = self
                    .slibc_consts
                    .get(*name)
                    .ok_or_else(|| format!("{}: unknown slibc constant `{name}`", spec.path))?;
                let value = ctype::const_expr(expr, ty, &self.types)
                    .map_err(|err| format!("{}: constant `{name}`: {err}", spec.path))?;
                let _ = writeln!(out, "#define {name} {}", parenthesise(&value));
            }
            // Contract constants keep contract order: it groups related values
            // and puts a value ahead of the constant that refers to it.
            for (name, item) in self.ordered_consts(spec) {
                let value = ctype::const_expr(&item.expr, &item.ty, &self.types)
                    .map_err(|err| format!("{}: constant `{name}`: {err}", spec.path))?;
                if item.ty.ends_with(HANDLER_TYPE) && !value.starts_with("((") {
                    let _ = writeln!(out, "#define {name} (({HANDLER_TYPE}){value})");
                    continue;
                }
                let _ = writeln!(out, "#define {name} {}", parenthesise(&value));
            }

            // POSIX defines each file-type test as exactly this comparison
            // against `S_IFMT`, so the set follows mechanically from the
            // contract's own `S_IF*` constants: `S_IFREG` gives `S_ISREG`.
            // Without them no C program can read a `struct stat`.
            let type_bits: Vec<&str> = self
                .ordered_consts(spec)
                .into_iter()
                .map(|(name, _)| name)
                .filter(|name| name.starts_with("S_IF") && *name != "S_IFMT")
                .collect();
            for name in type_bits {
                // The derivation is mechanical for every type but the FIFO,
                // which POSIX spells `S_ISFIFO` rather than `S_ISIFO`.
                let test = match name {
                    "S_IFIFO" => "FIFO",
                    other => &other["S_IF".len()..],
                };
                let _ = writeln!(
                    out,
                    "#define S_IS{test}(mode) (((mode) & S_IFMT) == {name})"
                );
            }
        }

        if !spec.macros.is_empty() {
            out.push('\n');
            for name in spec.macros {
                let signature = self
                    .macros
                    .get(name)
                    .ok_or_else(|| format!("{}: unknown macro `{name}`", spec.path))?;
                let body = self
                    .macro_bodies
                    .get(name)
                    .ok_or_else(|| format!("{}: no C body for macro `{name}`", spec.path))?;
                let params: Vec<&str> = signature
                    .params
                    .iter()
                    .map(|param| param.name.as_str())
                    .collect();
                for param in &params {
                    if !body.contains(*param) {
                        return Err(format!(
                            "{}: the C body of `{name}` never mentions its parameter `{param}`",
                            spec.path
                        ));
                    }
                }
                let _ = writeln!(out, "#define {name}({}) {body}", params.join(", "));
            }
        }

        if !spec.variables.is_empty() {
            out.push('\n');
            for variable in spec.variables {
                let (name, ty) = self.variable(variable)?;
                let declaration = self
                    .types
                    .declare(&ty, name)
                    .map_err(|err| format!("{}: variable `{name}`: {err}", spec.path))?;
                let _ = writeln!(out, "extern {declaration};");
            }
        }

        if !spec.functions.is_empty() || !spec.extra.is_empty() {
            out.push('\n');
            for name in spec.functions {
                let signature = self
                    .functions
                    .get(name)
                    .ok_or_else(|| format!("{}: unknown function `{name}`", spec.path))?;
                let _ = writeln!(out, "{}", self.prototype(signature)?);
            }
            for declaration in spec.extra {
                let signature = crate::contract::parse_signature(declaration)
                    .map_err(|err| format!("{}: {err}", spec.path))?;
                let _ = writeln!(out, "{}", self.prototype(&signature)?);
            }
        }

        if declares_symbols {
            out.push_str("\n#ifdef __cplusplus\n}\n#endif\n");
        }
        let _ = writeln!(out, "\n#endif /* {guard} */");

        if !spec.raw_unguarded.is_empty() {
            out.push('\n');
            for line in spec.raw_unguarded {
                let _ = writeln!(out, "{line}");
            }
        }
        Ok(out)
    }

    /// A `variables` entry: `"name"` takes its type from the contract's own
    /// `extern` declaration, and `"name: <rust type>"` declares a slibc object
    /// the contract has no reason to mention (`stdin` and friends).
    pub fn variable<'entry>(&self, entry: &'entry str) -> Result<(&'entry str, String), String> {
        match entry.split_once(':') {
            Some((name, ty)) => Ok((name.trim(), ty.trim().to_string())),
            None => {
                let name = entry.trim();
                let item = self.statics.get(name).ok_or_else(|| {
                    format!("`{name}` is not declared as an object by the contract")
                })?;
                Ok((name, item.ty.clone()))
            }
        }
    }

    /// The header's constants, in contract order.
    fn ordered_consts(&self, spec: &HeaderSpec) -> Vec<(&str, &Const)> {
        self.consts
            .iter()
            .filter(|(name, _)| owns(spec, name))
            .map(|(name, item)| (*name, *item))
            .collect()
    }

    fn render_type(&self, def: &TypeDef<'_>) -> Result<String, String> {
        let mut out = String::new();
        match def {
            TypeDef::Raw(line) => {
                let _ = writeln!(out, "{line}");
            }
            TypeDef::Alias { name, underlying } => {
                if *name == HANDLER_TYPE {
                    out.push_str(HANDLER_TYPEDEF);
                    return Ok(out);
                }
                let declaration = self
                    .types
                    .declare(underlying, name)
                    .map_err(|err| format!("typedef `{name}`: {err}"))?;
                let guard = STDDEF_TYPEDEFS
                    .iter()
                    .find(|(shared, _)| shared == name)
                    .map(|(_, guard)| *guard);
                if CXX_KEYWORDS.contains(name) {
                    let _ = writeln!(out, "#ifndef __cplusplus");
                }
                if let Some(guard) = guard {
                    let _ = writeln!(out, "#ifndef {guard}");
                    let _ = writeln!(out, "#define {guard}");
                }
                let _ = writeln!(out, "typedef {declaration};");
                if guard.is_some() {
                    let _ = writeln!(out, "#endif");
                }
                if CXX_KEYWORDS.contains(name) {
                    let _ = writeln!(out, "#endif");
                }
            }
            TypeDef::Opaque(name) => {
                let _ = writeln!(out, "typedef struct _slibc_{} {name};", name.to_lowercase());
            }
            TypeDef::Struct(item) if item.name == SIGVAL => out.push_str(SIGVAL_UNION),
            TypeDef::Struct(item) => {
                if let Some(field) = item
                    .fields
                    .iter()
                    .find(|field| CXX_KEYWORDS.contains(&field.name.as_str()))
                {
                    return Err(format!(
                        "`{}` has a field named `{}`, which C++ reserves; rename it at the \
                         declaration",
                        item.name, field.name
                    ));
                }
                let typedef = Types::is_typedef_shaped(&item.name);
                if item.name == "siginfo_t" {
                    out.push_str(SIGINFO_KILL);
                }
                if typedef {
                    let _ = writeln!(out, "typedef struct {{");
                } else {
                    let _ = writeln!(out, "struct {} {{", item.name);
                }
                // A zero-length array is how the contract states an alignment
                // that no field would otherwise force; C has no such field, so
                // it becomes an attribute on the type.
                let mut align = None;
                let mut fields = item.fields.iter().peekable();
                while let Some(field) = fields.next() {
                    if let Some(bytes) = zero_length_array(&field.ty, &self.types) {
                        align = Some(bytes);
                        continue;
                    }
                    if field.ty.ends_with("sighandler_t") {
                        out.push_str(HANDLER_SLOT);
                        continue;
                    }
                    if item.name == "siginfo_t" && field.name == "_pad" {
                        out.push_str(SIGINFO_PAYLOAD);
                        continue;
                    }
                    if field.ty.ends_with(SIGVAL) {
                        let _ = writeln!(out, "    union {SIGVAL} {};", field.name);
                        continue;
                    }
                    // Linux's Rust spelling of a stat time is two fields,
                    // `st_mtime` and `st_mtime_nsec`; C's is one `timespec`,
                    // `st_mtim`, with `st_mtime` a macro for its seconds.
                    if let Some(stem) = field.name.strip_suffix("time")
                        && fields
                            .peek()
                            .is_some_and(|next| next.name == format!("{}_nsec", field.name))
                    {
                        fields.next();
                        let _ = writeln!(out, "    struct timespec {stem}tim;");
                        continue;
                    }
                    let declaration = self
                        .types
                        .declare(&field.ty, &field.name)
                        .map_err(|err| format!("`{}.{}`: {err}", item.name, field.name))?;
                    let _ = writeln!(out, "    {declaration};");
                }
                let align = match align {
                    Some(bytes) => format!(" __slibc_aligned({bytes})"),
                    None => String::new(),
                };
                if typedef {
                    let _ = writeln!(out, "}}{align} {};", item.name);
                } else {
                    let _ = writeln!(out, "}}{align};");
                }
                if item.name == "siginfo_t" {
                    out.push_str(SIGINFO_MEMBERS);
                }
            }
        }
        Ok(out)
    }

    fn prototype(&self, signature: &Signature) -> Result<String, String> {
        if CXX_KEYWORDS.contains(&signature.name.as_str()) {
            return Err(format!(
                "`{}` is an entry point named with a C++ keyword",
                signature.name
            ));
        }
        let mut params: Vec<String> = Vec::new();
        for param in &signature.params {
            if CXX_KEYWORDS.contains(&param.name.as_str()) {
                return Err(format!(
                    "`{}` names a parameter `{}`, which C++ reserves; rename it at the \
                     declaration",
                    signature.name, param.name
                ));
            }
            params.push(
                self.types
                    .declare(&param.ty, &param.name)
                    .map_err(|err| format!("`{}` parameter `{}`: {err}", signature.name, err))?,
            );
        }
        if signature.variadic {
            params.push("...".to_string());
        }
        let params = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        let (noreturn, ret) = match signature.ret.as_str() {
            "!" => ("__slibc_noreturn ", "void".to_string()),
            "()" => ("", "void".to_string()),
            other => (
                "",
                self.types
                    .declare(other, "")
                    .map_err(|err| format!("`{}` return type: {err}", signature.name))?
                    .trim()
                    .to_string(),
            ),
        };
        let spacer = if ret.ends_with('*') { "" } else { " " };
        Ok(format!(
            "{noreturn}{ret}{spacer}{}({params});",
            signature.name
        ))
    }
}

/// Wraps a `#define` value in parentheses, which is right for every value
/// except a brace initialiser: `({ ... })` is a GNU statement expression, not
/// an aggregate.
fn parenthesise(value: &str) -> String {
    if value.starts_with('{') {
        value.to_string()
    } else {
        format!("({value})")
    }
}

/// Whether `spec` claims constant `name`, and how specifically. `None` means
/// no pattern matched.
pub fn claim(spec: &HeaderSpec, name: &str) -> Option<usize> {
    spec.consts
        .iter()
        .filter_map(|pattern| match pattern.strip_suffix('*') {
            Some(prefix) => name.starts_with(prefix).then_some(prefix.len()),
            None => (*pattern == name).then_some(usize::MAX),
        })
        .max()
}

fn owns(spec: &HeaderSpec, name: &str) -> bool {
    let Some(mine) = claim(spec, name) else {
        return false;
    };
    // Another header may match the same name with a more specific pattern;
    // `build.rs` has already rejected ties, so `>` is decisive.
    !crate::decls::HEADERS
        .iter()
        .any(|other| claim(other, name).is_some_and(|theirs| theirs > mine))
}

/// `Some(alignment)` if `ty` is a zero-length array.
fn zero_length_array(ty: &str, types: &Types) -> Option<usize> {
    let body = ty.strip_prefix('[')?.strip_suffix(']')?;
    let (elem, len) = body.split_once(';')?;
    if len.trim() != "0" {
        return None;
    }
    match types.abi(elem.trim()) {
        ctype::Abi::Int { bytes, .. } => Some(bytes as usize),
        _ => Some(8),
    }
}

/// C struct layout: field offsets and total size, for the `slopos-abi` pins.
pub struct Layout {
    pub size: usize,
    pub offsets: Vec<(String, usize)>,
}

pub fn layout(item: &Struct, types: &Types) -> Result<Layout, String> {
    let mut offset = 0usize;
    let mut align = 1usize;
    let mut offsets = Vec::new();
    for field in &item.fields {
        let (size, field_align) = size_and_align(&field.ty, types)?;
        align = align.max(field_align);
        if field_align != 0 {
            offset = offset.next_multiple_of(field_align);
        }
        offsets.push((field.name.clone(), offset));
        offset += size;
    }
    Ok(Layout {
        size: offset.next_multiple_of(align),
        offsets,
    })
}

fn size_and_align(ty: &str, types: &Types) -> Result<(usize, usize), String> {
    if let Some(body) = ty.strip_prefix('[').and_then(|ty| ty.strip_suffix(']')) {
        let (elem, len) = body
            .split_once(';')
            .ok_or_else(|| format!("array without a length: `{ty}`"))?;
        let len = types.array_len(len)?;
        let (size, align) = size_and_align(elem.trim(), types)?;
        return Ok((size * len, align));
    }
    match types.abi(ty) {
        ctype::Abi::Ptr => Ok((8, 8)),
        ctype::Abi::Int { bytes, .. } => Ok((bytes as usize, bytes as usize)),
        other => Err(format!(
            "cannot size `{ty}` (classified {})",
            other.describe()
        )),
    }
}

/// `_SLIBC_SYS_TYPES_H` from `sys/types.h`.
fn guard_name(path: &str) -> String {
    let mut out = String::from("_SLIBC_");
    for ch in path.chars() {
        out.push(if ch.is_ascii_alphanumeric() {
            ch.to_ascii_uppercase()
        } else {
            '_'
        });
    }
    out
}

/// The umbrella header: every generated header, in path order.
pub fn umbrella(source: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "/* slibc.h — every slibc header at once.");
    let _ = writeln!(out, " *");
    let _ = writeln!(
        out,
        " * Generated by slibc/build.rs from {source}; do not edit."
    );
    let _ = writeln!(out, " *");
    let _ = writeln!(
        out,
        " * A C program links `crt0.o` and `libc.a` and includes this, or the individual"
    );
    let _ = writeln!(out, " * headers below.");
    let _ = writeln!(out, " */");
    let _ = writeln!(out, "#ifndef _SLIBC_H");
    let _ = writeln!(out, "#define _SLIBC_H\n");
    let mut paths: Vec<&str> = crate::decls::HEADERS.iter().map(|spec| spec.path).collect();
    paths.sort_unstable();
    for path in paths {
        let _ = writeln!(out, "#include <{path}>");
    }
    let _ = writeln!(out, "\n#endif /* _SLIBC_H */");
    out
}

/// `sighandler_t` is an integer in the contract, which is the `libc` crate's
/// convention and the right one for Rust — `SIG_DFL` and `SIG_IGN` are zero
/// and one. C code assigns a function to it, so the header spells it as the
/// function pointer POSIX and glibc do, and every constant of that type is
/// emitted as a cast. The two renderings are the same eight bytes.
const HANDLER_TYPE: &str = "sighandler_t";
const HANDLER_TYPEDEF: &str = "typedef void (*sighandler_t)(int);\n";

/// POSIX gives one storage slot in `struct sigaction` two names with two
/// function-pointer types.
const HANDLER_SLOT: &str = "    union {
        sighandler_t sa_handler;
        void (*sa_sigaction)(int, siginfo_t *, void *);
    };
";

/// `siginfo_t`'s payload is 29 opaque ints in the contract, which is the
/// `libc` crate's shape; the Rust side reads it through accessor methods. C
/// names the fields, so the header overlays them on the same bytes, at Linux's
/// offsets: the union behind the three header ints starts at 16, one int into
/// `_pad`. A tagged struct declared outside the union, and macros for the
/// member names as glibc has them, keep this standard C++ as well as C.
const SIGINFO_KILL: &str = "struct __slibc_siginfo_kill {
    int __si_fill;
    pid_t __si_pid;
    uid_t __si_uid;
    int __si_status;
};
";
const SIGINFO_PAYLOAD: &str = "    union {
        int _pad[29];
        struct __slibc_siginfo_kill __si_fields;
    };
";
const SIGINFO_MEMBERS: &str = "#define si_pid __si_fields.__si_pid
#define si_uid __si_fields.__si_uid
#define si_status __si_fields.__si_status
";

/// POSIX's `union sigval`. The contract has the pointer arm only, as the
/// `libc` crate does; `sival_int` is the other arm of the same eight bytes.
const SIGVAL: &str = "sigval";
const SIGVAL_UNION: &str = "union sigval {
    int sival_int;
    void *sival_ptr;
};
";

/// Builds the `name -> TypeDef` index from the contract and the shared table.
pub fn index_types<'a>(
    aliases: &'a [Field],
    structs: &'a [Struct],
    opaques: &'a [String],
    raw: &'a str,
) -> BTreeMap<&'a str, TypeDef<'a>> {
    let mut out = BTreeMap::new();
    for alias in aliases {
        out.insert(
            alias.name.as_str(),
            TypeDef::Alias {
                name: &alias.name,
                underlying: &alias.ty,
            },
        );
    }
    for item in structs {
        out.insert(item.name.as_str(), TypeDef::Struct(item));
    }
    for name in opaques {
        out.insert(name.as_str(), TypeDef::Opaque(name));
    }
    out.insert("va_list", TypeDef::Raw(raw));
    out
}
