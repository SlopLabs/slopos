//! The declaration table: which header owns which contract declaration, the
//! libc types the contract reaches through `crate::`, the C bodies of the
//! contract's function-like macros, and the C entry points slibc defines that
//! the contract does not declare.
//!
//! Nothing here restates a *type*, a *constant value* or a *contract
//! signature*: those are parsed out of the patch. This file is routing plus
//! the three things a patch cannot contain — a POSIX header layout, a C macro
//! body, and the declarations for slibc's non-`libc`-declared C surface.
//!
//! Every list is checked for completeness by `build.rs`: a contract item that
//! no header claims, a header entry that the contract does not define, a macro
//! without a body, or a body that ignores one of its parameters is a build
//! error. That is what keeps the table honest as the contract changes.

/// One generated header.
pub struct HeaderSpec {
    pub path: &'static str,
    /// Rendered into the file's banner comment.
    pub summary: &'static str,
    /// `#include <...>` lines, in order.
    pub includes: &'static [&'static str],
    /// Contract (or shared-libc) types this header defines, in emission order:
    /// a struct must follow the types its fields name.
    pub types: &'static [&'static str],
    /// Constant name patterns. A trailing `*` is a prefix wildcard; the most
    /// specific pattern wins, and an exact name beats every wildcard.
    pub consts: &'static [&'static str],
    /// `pub const` items taken from slibc's own source rather than from the
    /// contract, for C macros the `libc` crate has no reason to declare.
    pub slibc_consts: &'static [&'static str],
    /// Contract `f!`/`safe_f!` items, emitted as C function-like macros.
    pub macros: &'static [&'static str],
    /// Contract entry points, emitted as prototypes.
    pub functions: &'static [&'static str],
    /// C entry points slibc exports that the contract does not declare,
    /// written in the contract's own signature syntax and ABI-checked against
    /// the real export.
    pub extra: &'static [&'static str],
    /// Exported objects, as `name: <rust type>`, ABI-checked the same way.
    pub variables: &'static [&'static str],
    /// Literal C lines. Each one is justified in a comment at its use site;
    /// they exist because C needs a spelling the Rust contract has no way to
    /// carry.
    pub raw: &'static [&'static str],
}

